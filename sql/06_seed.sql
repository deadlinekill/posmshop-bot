-- Справочники каталога (тестовый набор POS-материалов).
SET ROLE posm_owner;

INSERT INTO shop.categories (name, sort_order) VALUES
    ('Держатели информации', 1),
    ('Ценникодержатели', 2),
    ('Полочные разделители', 3),
    ('Рамы и крепления', 4),
    ('Кассеты цен', 5),
    ('Рекламные стойки', 6);

INSERT INTO shop.categories (parent_id, name, sort_order)
SELECT id, sub.name, sub.ord
FROM shop.categories c
JOIN (VALUES ('Держатели информации', 'Настольные', 1),
             ('Держатели информации', 'Настенные', 2),
             ('Ценникодержатели', 'Полочные', 1),
             ('Ценникодержатели', 'Для корзин и сеток', 2)) AS sub(parent, name, ord)
  ON c.name = sub.parent;

INSERT INTO shop.products (category_id, sku, name, price)
SELECT c.id, p.sku, p.name, p.price
FROM (VALUES
    ('Настольные', 'DI-A5-01', 'Держатель A5 настольный, оргстекло', 145.00),
    ('Настольные', 'DI-A4-01', 'Держатель A4 настольный, оргстекло', 210.00),
    ('Настенные', 'DI-A4-W1', 'Карман A4 настенный, ПЭТ', 120.00),
    ('Полочные', 'PC-10', 'Ценникодержатель полочный DBR 39 мм', 85.00),
    ('Полочные', 'PC-12', 'Ценникодержатель полочный DBR 26 мм', 70.00),
    ('Для корзин и сеток', 'PC-K20', 'Ценникодержатель на корзину', 64.00),
    ('Полочные разделители', 'D-30', 'Разделитель полочный 300 мм', 120.00),
    ('Полочные разделители', 'D-40', 'Разделитель полочный 400 мм', 135.00),

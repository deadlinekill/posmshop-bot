def money(value: Decimal | int | float) -> str:
    return f"{Decimal(value):,.2f}".replace(",", " ").replace(".", ",") + " ₽"


def h(text: object) -> str:
    """Экранирование данных пользователя перед вставкой в HTML-сообщение."""
    return escape(str(text))
